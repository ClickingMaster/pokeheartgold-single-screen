void BattleArcadeData_Init(ArcadeContext *ctx, u32 resume) {
    if (resume == FALSE) {
        BattleArcadeData_InitNew(ctx);
    } else {
        BattleArcadeData_InitResume(ctx);
    }
}

void BattleArcadeData_InitNew(ArcadeContext *ctx) {
    s32 rank = BattleArcade_GetRound(ctx);
    u8 battleNo;
    u32 count;
    u32 multiplayer;
    u32 *unk320;
    u32 i;

    BattleArcade_GetRoundTrainerIds(ctx->type, rank, ctx->trainerIds, 14);
    battleNo = ctx->battleNo;
    count = BattleArcade_GetOpponentMonCount(ctx->type, 1);
    multiplayer = BattleArcade_MultiplayerCheck(ctx->type);
    unk320 = ctx->personalities;
    FrontierTrainer_GenerateMons(count, ctx->trainerIds[battleNo], ctx->trainerIds[battleNo + 7], ctx->setIds, ctx->opponentMons, ctx->ivs, unk320, multiplayer);

    rank = BattleArcade_GetRound(ctx);
    for (i = 0; i < 3; i++) {
        if (rank >= gBattleArcadeRoundCursorSpeeds[i * 2]) {
            ctx->cursorSpeed = gBattleArcadeRoundCursorSpeeds[i * 2 + 1];
            return;
        }
    }
}

#pragma force_active on
void BattleArcadeData_InitResume(ArcadeContext *ctx) {
    ArcadeFrontierMon frontierMons[6];
    u16 monIds[6];
    u32 unkFlags[2];
    u32 unkValues[6];
    int i;
    Pokemon *mon;

    BattleArcadeData_RestoreHeldItems(ctx);
    for (i = 0; i < 14; i++) {
        ctx->trainerIds[i] = ArcadeChallenge_GetField((void *)ctx->challenge, 5, (u8)i, 0, 0);
    }
    for (i = 0; i < 4; i++) {
        monIds[i] = ArcadeChallenge_GetField((void *)ctx->challenge, 7, (u8)i, 0, 0);
        ctx->setIds[i] = monIds[i];
    }
    FrontierMon_GenerateList(frontierMons, monIds, (u8 *)unkFlags, NULL, unkValues, 4, HEAP_ID_FIELD2, 205);
    mon = AllocMonZeroed(HEAP_ID_FIELD2);
    for (i = 0; i < 4; i++) {
        FrontierMon_ToPokemon(&frontierMons[i], mon, BattleArcade_GetMonLevel(ctx));
        BattleArcade_AddMonToParty(ctx, ctx->opponentParty, mon);
    }
    Heap_Free(mon);
}
