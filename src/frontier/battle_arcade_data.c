// Starts with the Pokemon picked by unk20 and puts the first one that can fall asleep to sleep.
void BattleArcade_Event_Sleep(ArcadeContext *ctx, Party *party, int count) {
    s32 skipped = 0;
    u8 slot = ctx->unk20 % count;
    s32 i;

    for (i = 0; i < count; i++) {
        Pokemon *mon = Party_GetMonByIndex(party, slot);
        u32 ability = GetMonData(mon, MON_DATA_ABILITY, NULL);
        if (ability == ABILITY_INSOMNIA || ability == ABILITY_VITAL_SPIRIT) {
            slot++;
            skipped++;
            if (slot >= (u32)count) {
                slot = 0;
            }
        } else {
            u32 status = LCRandom() % 4 + 2;
            SetMonData(mon, MON_DATA_STATUS, &status);
            break;
        }
    }
    if (skipped >= count) {
        ctx->unk1F = TRUE;
    }
}

