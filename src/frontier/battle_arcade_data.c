u32 ov80_02235324(ArcadeContext *ctx) {
    u32 type = ctx->type;
    u32 round = ctx->round;
    u32 result;

    if (type <= 1) {
        result = round >= 8 ? 6 : ov80_0223C01C[round];
    } else {
        result = round >= 8 ? 0x11 : ov80_0223C028[round];
    }
    if (type == 0) {
        u16 winStreak = ctx->winStreak;
        if (winStreak == 0x15 || winStreak == 0x31) {
            result = 0x14;
        }
    }
    return result;
}

