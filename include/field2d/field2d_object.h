#ifndef POKEHEARTGOLD_FIELD2D_FIELD2D_OBJECT_H
#define POKEHEARTGOLD_FIELD2D_FIELD2D_OBJECT_H

// The values a 2D field object exposes through Field2DObject_GetParam / Field2DObject_SetParam.
enum Field2DObjectParam {
    FIELD2D_OBJECT_PARAM_X,
    FIELD2D_OBJECT_PARAM_Y,
    FIELD2D_OBJECT_PARAM_PREV_X,
    FIELD2D_OBJECT_PARAM_PREV_Y,
    FIELD2D_OBJECT_PARAM_ID,
    FIELD2D_OBJECT_PARAM_ACTION,
    FIELD2D_OBJECT_PARAM_DIRECTION,
    FIELD2D_OBJECT_PARAM_SPRITE_ID,
    FIELD2D_OBJECT_PARAM_ACTION_FRAME,
    FIELD2D_OBJECT_PARAM_ACTION_DURATION,
    FIELD2D_OBJECT_PARAM_STATE_FRAMES,
};

// The actions of a 2D field object (Field2DMove.action, Field2DCommand.action).
enum Field2DObjectAction {
    FIELD2D_ACTION_STAND,
    FIELD2D_ACTION_TURN,
    FIELD2D_ACTION_WALK,
    FIELD2D_ACTION_RUN,
    FIELD2D_ACTION_PAUSE,
    FIELD2D_ACTION_BUMP,
    FIELD2D_ACTION_WALK_SLOW,
    FIELD2D_ACTION_WALK_FAST,
    FIELD2D_ACTION_WALK_IN_PLACE_VERY_FAST,
    FIELD2D_ACTION_WALK_IN_PLACE_FAST,
    FIELD2D_ACTION_WALK_IN_PLACE,
    FIELD2D_ACTION_WALK_IN_PLACE_SLOW,
    FIELD2D_ACTION_COUNT,
};

#endif // POKEHEARTGOLD_FIELD2D_FIELD2D_OBJECT_H
